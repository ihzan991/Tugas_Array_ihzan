// Membuat function menghitung luas
function hitungLuasPersegiPanjang(panjang, lebar) {
    const luas = panjang * lebar;
    return luas;
}

// Memanggil function
const hasil = hitungLuasPersegiPanjang(10, 5);

console.log("Panjang: 10");
console.log("Lebar: 5");
